def render_logo(console: Console | None = None) -> Text:
    """Render the polished, high-contrast celestial lunar logo using Rich Text."""
    text = Text()
    for row in LOGO_ROWS:
        for seg, rgb in row:
            if rgb is not None:
                r, g, b = rgb
                is_bold = rgb[0] >= 230
                text.append(seg, style=Style(color=Color.from_rgb(r, g, b), bold=is_bold))
            else:
                text.append(seg)
        text.append("\n")

    if console is not None:
        console.print(text, soft_wrap=True)

    return text
